"""Writes the app's translated string resources from the language files in this folder.

Usage (from the repository root):  python3 tools/i18n/gen.py

Each language file (en.py, vi.py, ...) holds S (strings), P (plurals) and A (string arrays).
en.py is the reference: every other language must have exactly its keys, the same format
arguments and the same number of array entries. The script refuses to write anything when a
language does not match, so a missing or broken translation is caught before it ships.

It also writes res/xml/locales_config.xml, which lists the languages for the per-app language
setting on Android 13 and later. Re-run it after changing any language file, and commit the
generated XML with it. The XML can also be edited by hand; LocaleResourcesTest checks it
either way.
"""
import importlib.util
import pathlib
import re
import sys

HERE = pathlib.Path(__file__).resolve().parent
RES = HERE.parent.parent / "app" / "src" / "main" / "res"

# (language file, resource folder, BCP 47 tag for the per-app language list)
LANGUAGES = [
    ("en", "values", "en"),
    ("vi", "values-vi", "vi"),
    ("zh_hans", "values-b+zh+Hans", "zh-Hans"),
    ("zh_hant", "values-b+zh+Hant", "zh-Hant"),
    ("ko", "values-ko", "ko"),
    ("ja", "values-ja", "ja"),
    ("hi", "values-hi", "hi"),
    ("th", "values-th", "th"),
    ("id", "values-in", "in"),
    ("es", "values-es", "es"),
    ("pt", "values-pt", "pt"),
    ("fr", "values-fr", "fr"),
]

# Plural categories each language needs (CLDR). Languages without plural forms use only "other".
PLURAL_FORMS = {
    "en": {"one", "other"}, "hi": {"one", "other"},
    "es": {"one", "many", "other"}, "pt": {"one", "many", "other"}, "fr": {"one", "many", "other"},
}

FORMAT_ARG = re.compile(r"%(\d+)\$([sd])")


def load(name):
    spec = importlib.util.spec_from_file_location(name, HERE / f"{name}.py")
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


def args_of(text):
    if re.search(r"%(?!\d+\$[sd])", text):
        raise ValueError(f"stray % or non-positional format in: {text!r}")
    return sorted(set(FORMAT_ARG.findall(text)))


def escape(text):
    text = text.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;")
    text = text.replace("\\", "\\\\").replace("'", "\\'").replace('"', '\\"').replace("\n", "\\n")
    if text.startswith(("@", "?")):
        text = "\\" + text
    return text


def check(name, lang, ref):
    errors = []
    for kind in ("S", "P", "A"):
        mine, base = getattr(lang, kind), getattr(ref, kind)
        for key in base.keys() - mine.keys():
            errors.append(f"{name}: missing {kind} {key}")
        for key in mine.keys() - base.keys():
            errors.append(f"{name}: unknown {kind} {key}")
    for key, text in lang.S.items():
        if key in ref.S and args_of(text) != args_of(ref.S[key]):
            errors.append(f"{name}: {key} has format args {args_of(text)}, English has {args_of(ref.S[key])}")
    need = PLURAL_FORMS.get(name, {"other"})
    for key, forms in lang.P.items():
        if set(forms) != need:
            errors.append(f"{name}: plural {key} has {sorted(forms)}, needs {sorted(need)}")
        ref_args = args_of(ref.P[key]["other"]) if key in ref.P else None
        for q, text in forms.items():
            if ref_args is not None and args_of(text) != ref_args:
                errors.append(f"{name}: plural {key}/{q} has format args {args_of(text)}, English has {ref_args}")
    for key, items in lang.A.items():
        if key in ref.A and len(items) != len(ref.A[key]):
            errors.append(f"{name}: array {key} has {len(items)} items, English has {len(ref.A[key])}")
        if len(set(items)) != len(items):
            errors.append(f"{name}: array {key} has duplicates")
        for item in items:
            if args_of(item):
                errors.append(f"{name}: array {key} item {item!r} must not contain format args")
    return errors


def render(lang, default):
    out = ['<?xml version="1.0" encoding="utf-8"?>',
           "<!-- Generated by tools/i18n/gen.py from the language files there. Edit those, then re-run it. -->",
           "<resources>"]
    if default:
        out += ['    <!-- The brand name is the same in every language. Keep in step with Brand.NAME in :core. -->',
                '    <string name="app_name" translatable="false">Idol Chat Maker</string>',
                '    <!-- Under the launcher icon the full name would be cut off, so the icon shows the short form. -->',
                '    <string name="launcher_name" translatable="false">Idol Chat</string>']
    for key in sorted(lang.S):
        out.append(f'    <string name="{key}">{escape(lang.S[key])}</string>')
    for key in sorted(lang.P):
        out.append(f'    <plurals name="{key}">')
        for q in ("zero", "one", "two", "few", "many", "other"):
            if q in lang.P[key]:
                out.append(f'        <item quantity="{q}">{escape(lang.P[key][q])}</item>')
        out.append("    </plurals>")
    for key in sorted(lang.A):
        out.append(f'    <string-array name="{key}">')
        out += [f"        <item>{escape(item)}</item>" for item in lang.A[key]]
        out.append("    </string-array>")
    out.append("</resources>")
    return "\n".join(out) + "\n"


def main():
    ref = load("en")
    langs = {name: load(name) for name, _, _ in LANGUAGES}
    errors = [e for name, lang in langs.items() for e in check(name, lang, ref)]
    if errors:
        print("\n".join(errors))
        sys.exit(1)
    for name, folder, _ in LANGUAGES:
        path = RES / folder / "strings.xml"
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(render(langs[name], default=(folder == "values")), encoding="utf-8")
        print(f"wrote {path.relative_to(RES.parent.parent.parent.parent)}")
    config = ['<?xml version="1.0" encoding="utf-8"?>',
              "<!-- Languages offered in the system's per-app language setting (Android 13+).",
              "     Generated by tools/i18n/gen.py; keep in step with the values-* folders. -->",
              '<locale-config xmlns:android="http://schemas.android.com/apk/res/android">']
    config += [f'    <locale android:name="{tag}" />' for _, _, tag in LANGUAGES]
    config.append("</locale-config>")
    (RES / "xml").mkdir(exist_ok=True)
    (RES / "xml" / "locales_config.xml").write_text("\n".join(config) + "\n", encoding="utf-8")
    print("wrote locales_config.xml")


if __name__ == "__main__":
    main()
